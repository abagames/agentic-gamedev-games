// Bundles the ES modules into one classic script so index.html runs from file://.
// Usage: node tools/build.mjs
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const strip = (src) =>
  src
    .replace(/^import[^;]*;\s*$/gms, "")
    .replace(/^export (?=(const|function|let|class)\b)/gm, "");
const read = (f) => readFile(resolve(root, f), "utf8");

// Each module becomes a scope that returns its exported names.
async function mod(file) {
  const src = await read(file);
  const names = [...src.matchAll(/^export (?:const|function|let|class) (\w+)/gm)].map((m) => m[1]);
  return { names, body: `(() => {\n${strip(src)}\nreturn { ${names.join(", ")} };\n})()` };
}
const core = await mod("game-core.js");
const bot = await mod("demo-bot.js");
const font = await mod("vector-font.js");
const audio = await mod("audio.js");
const out = [
  "// GENERATED by tools/build.mjs from the ES modules — do not edit.",
  "(() => {",
  '"use strict";',
  `const { ${core.names.join(", ")} } = ${core.body};`,
  `const { ${bot.names.join(", ")} } = ${bot.body};`,
  `const { ${font.names.join(", ")} } = ${font.body};`,
  `const sfx = ${audio.body};`,
  strip(await read("main.js")),
  "})();",
].join("\n");
await writeFile(resolve(root, "game.js"), out);
console.log(`game.js written (${out.length} bytes)`);
